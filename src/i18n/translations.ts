const DICTIONARIES: Record<LanguageCode, Dict> = {
  en: EN,
  te: TE,
  hi: HI,
  ta: TA,
  kn: KN,
  ml: ML,
  mr: MR,
  bn: BN,
  gu: GU,
  pa: PA,
};

export function t(lang: LanguageCode, key: string): string {
  return DICTIONARIES[lang]?.[key] || EN[key] || key;
}

export function getSpeechLocale(lang: LanguageCode): string {
  return LANGUAGES.find((l) => l.code === lang)?.speechLocale || 'en-IN';
}
